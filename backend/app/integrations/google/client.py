"""
Google OAuth 2.0 API client for AgenSpace.

Handles authorization URL generation, server-side code exchange, Google identity
retrieval (using stable `sub`), and token refresh using standard Google endpoints.

Security constraints:
  - Requests Gmail full-mail access because the product explicitly supports read, send, modify, trash, and permanent delete operations.
  - Users receive a separate explicit confirmation for sending and every destructive message action.
  - Never logs raw authorization codes, client secrets, access tokens, or refresh tokens.
  - Raises descriptive, safe exceptions on communication or provider errors.
"""

import logging
import urllib.parse

import httpx

from app.core.config import get_settings

logger = logging.getLogger("agenspace.integrations.google.client")

GOOGLE_AUTH_URL = "https://accounts.google.com/o/oauth2/v2/auth"
GOOGLE_TOKEN_URL = "https://oauth2.googleapis.com/token"
GOOGLE_USERINFO_URL = "https://www.googleapis.com/oauth2/v3/userinfo"

GOOGLE_SCOPES: list[str] = [
    "openid",
    "https://www.googleapis.com/auth/userinfo.email",
    "https://mail.google.com/",
]


class GoogleOAuthError(Exception):
    """Base exception for Google OAuth errors."""


class GoogleConfigError(GoogleOAuthError):
    """Raised when Google OAuth credentials are not configured."""


class GoogleTokenExchangeError(GoogleOAuthError):
    """Raised when exchanging authorization code or refreshing token fails."""


class GoogleIdentityError(GoogleOAuthError):
    """Raised when fetching or verifying userinfo fails."""


def build_authorization_url(state: str) -> str:
    """
    Construct the Google OAuth 2.0 authorization URL.

    Parameters
    ----------
    state : str
        Cryptographically random state token generated by the state service.

    Returns
    -------
    str
        Full authorization redirect URL to Google accounts.
    """
    settings = get_settings()

    if not settings.google_client_id:
        raise GoogleConfigError(
            "GOOGLE_CLIENT_ID is not configured. Set this environment variable to enable Google integration."
        )
    if not settings.google_redirect_uri:
        raise GoogleConfigError(
            "GOOGLE_REDIRECT_URI is not configured. Set this environment variable to enable Google integration."
        )

    params = {
        "client_id": settings.google_client_id,
        "redirect_uri": settings.google_redirect_uri,
        "response_type": "code",
        "scope": " ".join(GOOGLE_SCOPES),
        "access_type": "offline",
        "prompt": "consent",
        "include_granted_scopes": "true",
        "state": state,
    }

    return f"{GOOGLE_AUTH_URL}?{urllib.parse.urlencode(params)}"


def exchange_code_for_tokens(code: str) -> dict:
    """
    Exchange authorization code for access and refresh tokens.

    Parameters
    ----------
    code : str
        The authorization code returned in Google's callback.

    Returns
    -------
    dict
        Parsed token dictionary containing 'access_token', optional 'refresh_token',
        'expires_in', and 'scope'.
    """
    settings = get_settings()

    if not settings.google_client_id or not settings.google_client_secret or not settings.google_redirect_uri:
        raise GoogleConfigError("Google OAuth credentials are not fully configured.")

    payload = {
        "code": code,
        "client_id": settings.google_client_id,
        "client_secret": settings.google_client_secret.get_secret_value(),
        "redirect_uri": settings.google_redirect_uri,
        "grant_type": "authorization_code",
    }

    try:
        with httpx.Client(timeout=15.0) as client:
            response = client.post(GOOGLE_TOKEN_URL, data=payload)
    except httpx.RequestError as exc:
        logger.error("HTTP request error during Google token exchange: %s", type(exc).__name__)
        raise GoogleTokenExchangeError("Failed to communicate with Google token endpoint.") from exc

    if response.status_code != 200:
        logger.warning("Google token exchange failed with HTTP status %d", response.status_code)
        raise GoogleTokenExchangeError("Google rejected authorization code or credentials.")

    try:
        data = response.json()
    except Exception as exc:
        raise GoogleTokenExchangeError("Invalid JSON received from Google token endpoint.") from exc

    if "access_token" not in data:
        raise GoogleTokenExchangeError("No access token present in Google token response.")

    return data


def fetch_google_userinfo(access_token: str) -> dict:
    """
    Fetch the authenticated user's identity from Google UserInfo.

    Parameters
    ----------
    access_token : str
        Valid Google access token.

    Returns
    -------
    dict
        Dictionary containing 'sub' (stable Google ID) and 'email'.
    """
    headers = {"Authorization": f"Bearer {access_token}"}

    try:
        with httpx.Client(timeout=15.0) as client:
            response = client.get(GOOGLE_USERINFO_URL, headers=headers)
    except httpx.RequestError as exc:
        logger.error("HTTP request error during Google userinfo retrieval: %s", type(exc).__name__)
        raise GoogleIdentityError("Failed to communicate with Google userinfo endpoint.") from exc

    if response.status_code != 200:
        logger.warning("Google userinfo failed with status %d", response.status_code)
        raise GoogleIdentityError("Failed to retrieve Google user profile.")

    try:
        data = response.json()
    except Exception as exc:
        raise GoogleIdentityError("Invalid JSON from Google userinfo endpoint.") from exc

    if "sub" not in data:
        raise GoogleIdentityError("Missing 'sub' identifier in Google userinfo response.")

    return data


def refresh_access_token(refresh_token: str) -> dict:
    """
    Refresh an expired Google access token using the stored refresh token.

    Parameters
    ----------
    refresh_token : str
        Decrypted Google refresh token.

    Returns
    -------
    dict
        Dictionary with 'access_token', 'expires_in', and optional updated 'refresh_token'.
    """
    settings = get_settings()

    if not settings.google_client_id or not settings.google_client_secret:
        raise GoogleConfigError("Google OAuth credentials are not fully configured.")

    payload = {
        "client_id": settings.google_client_id,
        "client_secret": settings.google_client_secret.get_secret_value(),
        "refresh_token": refresh_token,
        "grant_type": "refresh_token",
    }

    try:
        with httpx.Client(timeout=15.0) as client:
            response = client.post(GOOGLE_TOKEN_URL, data=payload)
    except httpx.RequestError as exc:
        logger.error("HTTP request error during Google token refresh: %s", type(exc).__name__)
        raise GoogleTokenExchangeError("Failed to communicate with Google token endpoint for refresh.") from exc

    if response.status_code != 200:
        logger.warning("Google token refresh failed with status %d", response.status_code)
        raise GoogleTokenExchangeError("Google refresh token expired, revoked, or invalid.")

    try:
        data = response.json()
    except Exception as exc:
        raise GoogleTokenExchangeError("Invalid JSON received from Google token refresh.") from exc

    if "access_token" not in data:
        raise GoogleTokenExchangeError("No access token in Google token refresh response.")

    return data
